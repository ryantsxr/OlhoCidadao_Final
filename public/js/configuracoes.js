function mostrarToast(mensagem, tipo = 'erro') {
    if (!mensagem) return;

    if (!document.getElementById('estilo-toast')) {
        const estilo = document.createElement('style');
        estilo.id = 'estilo-toast';
        estilo.textContent = `
            .toast-container {
                position: fixed;
                top: 20px;
                right: 20px;
                z-index: 9999;
                display: flex;
                flex-direction: column;
                gap: 10px;
            }
            .toast {
                min-width: 260px;
                max-width: 360px;
                padding: 14px 18px;
                border-radius: 10px;
                font-family: Poppins, sans-serif;
                font-size: 14px;
                line-height: 1.4;
                box-shadow: 0 8px 20px rgba(0,0,0,0.35);
                display: flex;
                align-items: flex-start;
                gap: 10px;
                animation: toast-entrar 0.3s ease-out;
            }
            .toast.erro { background: #3a1f24; border: 1px solid #ff5050; color: #ff9b9b; }
            .toast.sucesso { background: #1f3a22; border: 1px solid #6B8E4E; color: #B7CFA1; }
            .toast i { margin-top: 2px; }
            .toast.saindo { animation: toast-saida 0.3s ease-in forwards; }
            @keyframes toast-entrar {
                from { transform: translateX(120%); opacity: 0; }
                to { transform: translateX(0); opacity: 1; }
            }
            @keyframes toast-saida {
                from { transform: translateX(0); opacity: 1; }
                to { transform: translateX(120%); opacity: 0; }
            }
            @media (max-width: 480px) {
                .toast-container { left: 16px; right: 16px; top: 16px; }
                .toast { max-width: none; }
            }
        `;
        document.head.appendChild(estilo);
    }

    let container = document.querySelector('.toast-container');
    if (!container) {
        container = document.createElement('div');
        container.className = 'toast-container';
        document.body.appendChild(container);
    }

    const toast = document.createElement('div');
    toast.className = 'toast ' + (tipo === 'sucesso' ? 'sucesso' : 'erro');

    const icone = document.createElement('i');
    icone.className = 'fa-solid ' + (tipo === 'sucesso' ? 'fa-circle-check' : 'fa-circle-exclamation');

    const texto = document.createElement('span');
    texto.textContent = mensagem;

    toast.appendChild(icone);
    toast.appendChild(texto);
    container.appendChild(toast);

    setTimeout(() => {
        toast.classList.add('saindo');
        setTimeout(() => toast.remove(), 300);
    }, 4500);
}
