// FUNÇÕES DE APLICAÇÃO
function aplicarTamanhoFonte(tamanho) {
    if (tamanho === 'grande') {
        document.documentElement.style.fontSize = '120%';
    } else if (tamanho === 'extra-grande') {
        document.documentElement.style.fontSize = '140%';
    } else {
        document.documentElement.style.fontSize = '100%';
    }
}

/**
 * Aplica o idioma escolhido em TODOS os elementos da página que tiverem
 * o atributo data-i18n="<chave>". Assim, qualquer texto novo do site só
 * precisa desse atributo no HTML — não é preciso mexer no JS de novo.
 *
 * Exemplos de uso no HTML:
 *   <span id="texto-inicio" data-i18n="inicio"></span>
 *   <h1 data-i18n="titulo-config"></h1>
 *   <p data-i18n="sub-config"></p>
 *   <label data-i18n="tema-escuro"></label>
 *
 * Para inputs/placeholders, use data-i18n-placeholder="<chave>".
 * Para atributos title, use data-i18n-title="<chave>".
 */
function aplicarIdioma(siglaIdioma) {
    const t = traducoes[siglaIdioma];
    if (!t) {
        if (window.ocI18n) window.ocI18n.aplicar(siglaIdioma);
        return;
    }

    // Atualiza o texto interno de qualquer elemento marcado com data-i18n
    document.querySelectorAll('[data-i18n]').forEach((el) => {
        const chave = el.getAttribute('data-i18n');
        if (t[chave] !== undefined) {
            el.innerText = t[chave];
        }
    });

    // Atualiza placeholders (ex: campos de busca/formulário)
    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
        const chave = el.getAttribute('data-i18n-placeholder');
        if (t[chave] !== undefined) {
            el.setAttribute('placeholder', t[chave]);
        }
    });

    // Atualiza atributos title (tooltips)
    document.querySelectorAll('[data-i18n-title]').forEach((el) => {
        const chave = el.getAttribute('data-i18n-title');
        if (t[chave] !== undefined) {
            el.setAttribute('title', t[chave]);
        }
    });

    // Mantém compatibilidade com os IDs antigos, caso o data-i18n
    // ainda não tenha sido adicionado em algum HTML.
    const mapaIdsAntigos = {
        'texto-inicio': 'inicio',
        'texto-config': 'config',
        'titulo-principal-config': 'titulo-config'
    };
    Object.entries(mapaIdsAntigos).forEach(([id, chave]) => {
        const el = document.getElementById(id);
        if (el && t[chave] !== undefined) {
            el.innerText = t[chave];
        }
    });

    // Marca o idioma atual no <html> (útil para CSS/acessibilidade)
    document.documentElement.setAttribute('lang', siglaIdioma);

    // Traduz o restante da página (textos sem data-i18n, avisos, gráficos...).
    if (window.ocI18n) window.ocI18n.aplicar(siglaIdioma);
}

function obterConfiguracaoFormulario() {
    return {
        temaEscuro: document.getElementById('toggle-tema')?.checked ?? true,
        idioma: document.getElementById('select-idioma')?.value ?? 'pt-br',
        fonte: document.getElementById('select-fonte')?.value ?? 'padrao',
        altoContraste: document.getElementById('toggle-contraste')?.checked ?? false,
        modoDaltonico: document.getElementById('toggle-daltonico')?.checked ?? false,
        fonteLeitura: document.getElementById('toggle-leitura')?.checked ?? false
    };
}

function salvarConfiguracoes() {
    const config = obterConfiguracaoFormulario();
    localStorage.setItem('configOlhoCidadao', JSON.stringify(config));
    aplicarConfiguracaoVisual(config);
}

function aplicarConfiguracaoVisual(config) {
    aplicarTamanhoFonte(config.fonte);

    if (config.temaEscuro === false) {
        document.body.classList.add('tema-claro');
    } else {
        document.body.classList.remove('tema-claro');
    }

    document.body.classList.toggle('alto-contraste', config.altoContraste === true);
    document.body.classList.toggle('modo-daltonico', config.modoDaltonico === true);
    document.documentElement.classList.toggle('pre-modo-daltonico', config.modoDaltonico === true);
    document.body.classList.toggle('fonte-leitura', config.fonteLeitura === true);

    if (config.idioma) aplicarIdioma(config.idioma);
}

function carregarPreferenciasGlobais() {
    let config = window.CONFIG_SERVIDOR || null;

    if (!config) {
        const configSalva = localStorage.getItem('configOlhoCidadao');
        if (configSalva) {
            try {
                config = JSON.parse(configSalva);
            } catch (e) {
                localStorage.removeItem('configOlhoCidadao');
            }
        }
    }

    if (config) aplicarConfiguracaoVisual(config);
}

function preencherFormularioConfiguracoes(config = null) {
    if (!config) {
        const configSalva = localStorage.getItem('configOlhoCidadao');
        if (!configSalva) return;
        try {
            config = JSON.parse(configSalva);
        } catch (e) {
            return;
        }
    }

    const tTema = document.getElementById('toggle-tema');
    const sIdioma = document.getElementById('select-idioma');
    const sFonte = document.getElementById('select-fonte');
    const tContraste = document.getElementById('toggle-contraste');

    if (tTema) tTema.checked = config.temaEscuro === true;
    if (sIdioma) sIdioma.value = config.idioma || 'pt-br';
    if (sFonte) sFonte.value = config.fonte || 'padrao';
    if (tContraste) tContraste.checked = config.altoContraste === true;
    const tDalt = document.getElementById('toggle-daltonico');
    const tLeit = document.getElementById('toggle-leitura');
    if (tDalt) tDalt.checked = config.modoDaltonico === true;
    if (tLeit) tLeit.checked = config.fonteLeitura === true;
}

