document.addEventListener("DOMContentLoaded", () => {
    carregarPreferenciasGlobais();

    const btnSalvar = document.querySelector('.btn-salvar');
    const form = btnSalvar ? btnSalvar.closest('form') : null;

    if (window.CONFIG_SERVIDOR) {
        localStorage.setItem('configOlhoCidadao', JSON.stringify(window.CONFIG_SERVIDOR));
        preencherFormularioConfiguracoes(window.CONFIG_SERVIDOR);
        aplicarConfiguracaoVisual(window.CONFIG_SERVIDOR);
    }

    if (form) {
        form.addEventListener('submit', () => {
            localStorage.setItem('configOlhoCidadao', JSON.stringify(obterConfiguracaoFormulario()));
        });
    }

    const selectIdioma = document.getElementById('select-idioma');
    if (selectIdioma) {
        selectIdioma.addEventListener('change', () => aplicarIdioma(selectIdioma.value));
    }
});

